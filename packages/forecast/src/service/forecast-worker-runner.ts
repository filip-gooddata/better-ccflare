import type { EngineContext } from "../engine/model";
import type {
	DaytypesResult,
	LearnedDemand,
	Partition,
	RowChoice,
} from "../engine/learn/types";
import type { PaceFitState } from "../engine/pace/types";
import type { PlanJobResult, ScenarioLadderOverride } from "../engine/plan-job";
import type { EpochMs } from "../types";

/** The pooled series (buffers transferred), the instant it is fitted at, and the settings the learners start from. */
export interface SeriesPayload {
	start: EpochMs;
	units: Float64Array;
	censored: Uint8Array;
	timeZone: string;
	now: EpochMs;
	workDays: number;
	historyLookbackDays: number;
	historyHalfLifeDays: number;
	workStartSharePct: number;
	timeShiftMin: number;
}

/**
 * Jobs the forecast worker runs off the main thread, by name: what goes in and
 * what comes back. Both cross the worker boundary by structured clone, so they
 * are plain data. A new job adds an entry here and a handler in forecast-worker.ts.
 */
export interface ForecastWorkerJobs {
	/**
	 * E4 refit and F2 rows 2-8 in one job. E4 is fitted once, with the
	 * partition of `daytypes` (the last stored row-1 choice; null before the
	 * first, which fits the present partition). `pace` is that fit.
	 */
	refit: {
		payload: SeriesPayload & { daytypes: RowChoice<Partition> | null };
		result: { pace: PaceFitState; learned: LearnedDemand };
	};
	/**
	 * F2 row 1 (day types, DESIGN-F2 R3-2): `daytypes` is the stored choice
	 * (its served partition is served now) and `pending` the switch waiting
	 * for confirmation. Nothing pending: one full E4 fit per family partition,
	 * scored and selected. Pending: the nested comparison of present vs pending.
	 */
	daytypes: {
		payload: SeriesPayload & {
			daytypes: RowChoice<Partition> | null;
			pending: Partition | null;
		};
		result: DaytypesResult;
	};
	/**
	 * The scenario count, then the planner: the prepared context with the ladder's top rung of
	 * scenario days (buffers transferred) and the compute budget, which the worker turns into one
	 * deadline on its own clock. `ladder` is set by tests only. Answers what computeForecast reads.
	 */
	plan: {
		payload: {
			ctx: EngineContext;
			budgetMs: number;
			ladder?: ScenarioLadderOverride;
		};
		result: PlanJobResult;
	};
}

export type ForecastJobName = keyof ForecastWorkerJobs;

export type ForecastWorkerRequest = {
	[J in ForecastJobName]: {
		job: J;
		id: number;
		payload: ForecastWorkerJobs[J]["payload"];
	};
}[ForecastJobName];

export type ForecastWorkerReply =
	| { id: number; ok: true; result: unknown }
	/** `error` is the thrown error's name only, never its message. */
	| { id: number; ok: false; error: string };

export type ForecastJobFailure =
	/** The job threw inside the worker. */
	| "job-error"
	/** The worker failed to start, crashed, or answered out of protocol. */
	| "worker-error"
	/** The caller aborted. */
	| "stopped"
	/** A job of the same name is still running. */
	| "busy";

export type ForecastJobOutcome<R> =
	| { status: "ok"; result: R; ms: number }
	| { status: "timeout"; ms: number }
	| { status: "error"; reason: ForecastJobFailure; ms: number };

export interface ForecastJobOptions {
	timeoutMs: number;
	/** Buffers moved to the worker instead of copied; the caller's views are detached afterwards. */
	transfer?: Transferable[];
	signal?: AbortSignal;
}

export interface ForecastWorkerRunner {
	run<J extends ForecastJobName>(
		job: J,
		payload: ForecastWorkerJobs[J]["payload"],
		options: ForecastJobOptions,
	): Promise<ForecastJobOutcome<ForecastWorkerJobs[J]["result"]>>;
}

export interface ForecastWorkerRunnerOptions {
	/** Source worker module, used when no embedded code is built in. Defaults to ./forecast-worker.ts. */
	workerUrl?: string;
	/** The worker bundle the CLI build embeds, or "" in a checkout. */
	embeddedCode?: () => Promise<string>;
}

/**
 * The CLI build writes embedded-forecast-worker.ts (git-ignored, generated by
 * apps/cli). A checkout without a build has no such file, so it is imported
 * lazily and its absence means "run the source module".
 */
async function builtInWorkerCode(): Promise<string> {
	try {
		const mod = await import("./embedded-forecast-worker");
		return mod.EMBEDDED_FORECAST_WORKER_CODE;
	} catch {
		return "";
	}
}

/**
 * Runs each job in a fresh worker that is terminated when the job ends, times
 * out or is aborted (the pattern of database/integrity-check-runner.ts). Jobs of
 * different names may run side by side; one name never runs twice at once.
 */
export function createForecastWorkerRunner(
	options: ForecastWorkerRunnerOptions = {},
): ForecastWorkerRunner {
	const workerUrl =
		options.workerUrl ?? new URL("./forecast-worker.ts", import.meta.url).href;
	const embeddedCode = options.embeddedCode ?? builtInWorkerCode;
	const running = new Set<ForecastJobName>();
	let nextId = 1;

	const run = async <J extends ForecastJobName>(
		job: J,
		payload: ForecastWorkerJobs[J]["payload"],
		opts: ForecastJobOptions,
	): Promise<ForecastJobOutcome<ForecastWorkerJobs[J]["result"]>> => {
		const started = performance.now();
		const ms = () => Math.round(performance.now() - started);
		if (running.has(job)) return { status: "error", reason: "busy", ms: 0 };
		if (opts.signal?.aborted)
			return { status: "error", reason: "stopped", ms: 0 };
		running.add(job);
		let worker: Worker | undefined;
		let blobUrl: string | undefined;
		let timeoutHandle: ReturnType<typeof setTimeout> | undefined;
		let onAbort: (() => void) | undefined;
		try {
			const code = await embeddedCode();
			// An abort while the code loaded starts no worker.
			if (opts.signal?.aborted)
				return { status: "error", reason: "stopped", ms: ms() };
			if (code) {
				const source = Buffer.from(code, "base64").toString("utf8");
				blobUrl = URL.createObjectURL(
					new Blob([source], { type: "text/javascript" }),
				);
				worker = new Worker(blobUrl, { smol: true });
			} else {
				worker = new Worker(workerUrl);
			}
			// The proxy's shutdown never waits on a job (Bun's Worker has unref;
			// the DOM type in lib.dom does not declare it).
			(worker as Worker & { unref(): void }).unref();
			const id = nextId++;
			const live = worker;
			return await new Promise<
				ForecastJobOutcome<ForecastWorkerJobs[J]["result"]>
			>((resolve) => {
				live.onmessage = (event: MessageEvent<ForecastWorkerReply>) => {
					const reply = event.data;
					if (reply?.id !== id)
						resolve({ status: "error", reason: "worker-error", ms: ms() });
					else if (reply.ok)
						resolve({
							status: "ok",
							result: reply.result as ForecastWorkerJobs[J]["result"],
							ms: ms(),
						});
					else resolve({ status: "error", reason: "job-error", ms: ms() });
				};
				live.onerror = () =>
					resolve({ status: "error", reason: "worker-error", ms: ms() });
				timeoutHandle = setTimeout(
					() => resolve({ status: "timeout", ms: ms() }),
					opts.timeoutMs,
				);
				onAbort = () =>
					resolve({ status: "error", reason: "stopped", ms: ms() });
				opts.signal?.addEventListener("abort", onAbort, { once: true });
				const request = { job, id, payload } as ForecastWorkerRequest;
				live.postMessage(request, opts.transfer ?? []);
			});
		} catch {
			return { status: "error", reason: "worker-error", ms: ms() };
		} finally {
			if (timeoutHandle !== undefined) clearTimeout(timeoutHandle);
			if (onAbort) opts.signal?.removeEventListener("abort", onAbort);
			worker?.terminate();
			// The blob URL keeps the worker code alive until revoked.
			if (blobUrl !== undefined) URL.revokeObjectURL(blobUrl);
			running.delete(job);
		}
	};

	return { run };
}
