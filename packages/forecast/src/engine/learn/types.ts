import type { EpochMs } from "../../types";
import type { PaceFitState, PaceSeries } from "../pace/types";

/**
 * F2 demand-side learners. Every row scores its candidates out of sample and
 * `selectRow` (select.ts) decides, by the E4 method, whether the row serves a
 * value other than the setting it has today. Plain data only: a
 * `LearnedDemand` crosses the worker boundary.
 */

/** Weekday groups Mon..Sun: entry i is the group id of weekday i (0 = Monday). */
export type Partition = readonly number[];

/** Row 2: a pool shrinkage constant, `Infinity` for full pooling, or the hard 3-day fallback of today. */
export type PoolTau = number | "hard3";

export interface RowScores<V> {
	/** Stable id used in the log line. */
	row: string;
	/** Generated by the row's written rule; includes the present value. */
	candidates: V[];
	presentIndex: number;
	/** Per candidate, its rank in the row's written preference order (present = 0): the 1-SE tie-break. */
	preference: number[];
	/** Independent unit ids (day or week, per row). */
	units: number[];
	/** loss[c][u]: out-of-fold loss of candidate c aggregated over unit u (NaN = unscored). */
	loss: Float64Array[];
}

export interface RowChoice<V> {
	row: string;
	/** Candidates searched, including any dropped for having no finite loss. */
	m: number;
	floor: number;
	/** Units every kept candidate scored. */
	units: number;
	present: V;
	chosen: V;
	runnerUp: V | null;
	served: V;
	presentLoss: number;
	chosenLoss: number;
	gain: number;
	se: number;
	p: number;
	on: boolean;
	reason:
		| "on"
		| "present-best"
		| "below-floor"
		| "gain-le-se"
		| "bh"
		| "no-units";
}

/** Fits E4 with the given calendar partition; memoized per normalized partition within one job. */
export type PartitionFitter = (partition: Partition) => PaceFitState;

export interface LearnInput {
	/** The pooled five-minute series the refit worker fits E4 on. */
	series: PaceSeries;
	now: EpochMs;
	/** Work days per week as PaceContext.workDays (weekdays 1..workDays, Monday = 1, are work days). */
	workDays: number;
	historyLookbackDays: number;
	historyHalfLifeDays: number;
	workStartSharePct: number;
	timeShiftMin: number;
	/** Row 1: the full E4 fit under a candidate partition. The present partition returns the job's E4 fit. */
	fitWithPartition: PartitionFitter;
}

/** Inputs of `presentDemand`: the settings each row's present value comes from. */
export interface DemandSettings {
	historyLookbackDays: number;
	historyHalfLifeDays: number;
	workStartSharePct: number;
	timeShiftMin: number;
}

/** The served demand values; each equals its present value unless its row switched on. */
export interface LearnedDemand {
	/** One per row, in registry order; empty for `presentDemand`. */
	choices: RowChoice<unknown>[];
	/** Row 1: E4 calendar classes and scenario day pools. */
	partition: Partition;
	/** Row 2: pool shrinkage; "hard3" = today's 3-day fallback and empty-pool rule. */
	poolTau: PoolTau;
	/** Row 4: days of history the scenario day table looks back. */
	lookbackDays: number;
	/** Row 5: scenario day-weight half-life; `Infinity` = equal weights. */
	halfLifeDays: number;
	/** Row 16: work-start share and its sample of recent work days. */
	workStartSharePct: number;
	workStartSample: number;
	/** Row 18: scale bandwidth multiplier is 2^(k/2). */
	bandwidthK: number;
	/** Row 20: jitter bound in minutes. */
	jitterMin: number;
	/** Wall time of the learners, rounded ms; 0 for `presentDemand`. */
	ms: number;
}
