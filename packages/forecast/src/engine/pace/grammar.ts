import { DAY_BUCKETS, type PaceCalendar } from "./calendar";
import type { PaceCandidate } from "./types";

/** Pseudo-count (units) inside every log ratio (sandbox lib.ts C_UNITS). */
export const C_UNITS = 2;
/** A span with more than this share of censored buckets is dropped (sandbox lib.ts CENSOR_SHARE). */
export const CENSOR_SHARE = 0.1;
export const WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];
const LADDER_MIN = [
	15, 30, 60, 120, 240, 480, 960, 1440, 2880, 5760, 10080, 20160,
];
const lbl = (m: number) =>
	m % 1440 === 0 ? `${m / 1440}d` : m % 60 === 0 ? `${m / 60}h` : `${m}m`;

/**
 * The round-3 grammar with the widened lag and target-calendar families
 * (sandbox lib.ts grammar + model3b.ts grammar3 with lags and cal): 32 rolling
 * spans, same span 1-14 days earlier, calendar day 0-14 back, the last named
 * weekday, last ISO week (all, workdays), target weekday and clock-hour shares.
 * 101 candidates, generated by rule; specs are plain data.
 */
export function paceGrammar(): PaceCandidate[] {
	const R: PaceCandidate[] = [];
	for (const L of LADDER_MIN)
		for (const m of [0, 1, 3]) {
			const e = m * L;
			if (e > 10080) continue;
			R.push({
				id: `R:len${lbl(L)}:end${e ? lbl(e) : "0"}`,
				family: "R",
				long: L >= 2880 || e >= 2880,
				len: L / 5,
				end: e / 5,
			});
		}
	const S: PaceCandidate[] = [];
	for (let k = 1; k <= 14; k++)
		S.push({ id: `S:sameSpan-${k}d`, family: "S", long: k >= 7, k });
	const C: PaceCandidate[] = [];
	for (let k = 0; k <= 14; k++)
		C.push({ id: `C:day-${k}`, family: "C", long: k >= 7, k });
	const D: PaceCandidate[] = WEEKDAYS.map((w, wd) => ({
		id: `D:last${w}`,
		family: "D",
		long: true,
		wd,
	}));
	const W: PaceCandidate[] = [
		{ id: "W:lastWeek-all", family: "W", long: true, workdays: false },
		{ id: "W:lastWeek-workdays", family: "W", long: true, workdays: true },
	];
	const T: PaceCandidate[] = WEEKDAYS.map((w, wd) => ({
		id: `T:wd-${w}`,
		family: "T",
		long: true,
		wd,
	}));
	for (let h = 0; h < 24; h++)
		T.push({
			id: `T:hr-${String(h).padStart(2, "0")}`,
			family: "T",
			long: false,
			hour: h,
		});
	return [...R, ...S, ...C, ...D, ...W, ...T];
}

export function prefix(a: ArrayLike<number>, n = a.length): Float64Array {
	const p = new Float64Array(n + 1);
	for (let i = 0; i < n; i++) p[i + 1] = (p[i] as number) + (a[i] as number);
	return p;
}

/** Prefix sums of the usage, censoring and one baseline over the observed buckets. */
export interface SpanSums {
	PU: Float64Array;
	PC: Float64Array;
	PB: Float64Array;
}

/** log((U + c) / (B + c)) of the span [s, e), or NaN when out of range or censored (sandbox lib.ts lr). */
export function lr(P: SpanSums, s: number, e: number): number {
	if (s < 0 || e <= s || e > P.PU.length - 1) return Number.NaN;
	if (((P.PC[e] as number) - (P.PC[s] as number)) / (e - s) > CENSOR_SHARE)
		return Number.NaN;
	return Math.log(
		((P.PU[e] as number) - (P.PU[s] as number) + C_UNITS) /
			((P.PB[e] as number) - (P.PB[s] as number) + C_UNITS),
	);
}

/** Calendar facts the candidates read, with lazily built target-calendar prefix counts. */
export class GrammarContext {
	private readonly prevWeek: ([number, number] | null)[][];
	private readonly wdCount = new Map<number, Int32Array>();
	private readonly hourCount = new Map<number, Int32Array>();
	constructor(readonly cal: PaceCalendar) {
		const { days } = cal;
		// per day: the spans of the last complete ISO week before its own week (sandbox lib.ts W family)
		const byWeek = new Map<number, number[]>();
		for (let d = 0; d < days.length; d++) {
			const w = (days[d] as { week: number }).week;
			const list = byWeek.get(w);
			if (list) list.push(d);
			else byWeek.set(w, [d]);
		}
		const spanOf = (
			ds: number[],
			workdays: boolean,
		): [number, number] | null => {
			if (ds.length < 7) return null;
			const sel = workdays
				? ds.filter(
						(d) => cal.dtype[(days[d] as { first: number }).first] === 0,
					)
				: ds;
			if (!sel.length) return null;
			return [
				(days[sel[0] as number] as { first: number }).first,
				(days[sel[sel.length - 1] as number] as { end: number }).end,
			];
		};
		const weeks = [...byWeek.keys()];
		const perWeek = new Map<number, ([number, number] | null)[]>();
		weeks.forEach((w, q) => {
			const prev =
				q > 0 ? (byWeek.get(weeks[q - 1] as number) as number[]) : null;
			perWeek.set(
				w,
				prev ? [spanOf(prev, false), spanOf(prev, true)] : [null, null],
			);
		});
		this.prevWeek = days.map(
			(d) => perWeek.get(d.week) as ([number, number] | null)[],
		);
	}

	private counts(
		map: Map<number, Int32Array>,
		key: number,
		of: (i: number) => boolean,
	): Int32Array {
		let p = map.get(key);
		if (!p) {
			p = new Int32Array(this.cal.n + 1);
			for (let i = 0; i < this.cal.n; i++)
				p[i + 1] = (p[i] as number) + (of(i) ? 1 : 0);
			map.set(key, p);
		}
		return p;
	}

	/** Past span [s, e) of a span candidate at origin o for the target [a, b), or null. */
	span(
		c: PaceCandidate,
		o: number,
		a: number,
		b: number,
	): [number, number] | null {
		const { days, dayIdx } = this.cal;
		switch (c.family) {
			case "R": {
				const len = c.len as number;
				const end = c.end as number;
				return [o - end - len, o - end];
			}
			case "S": {
				const sh = (c.k as number) * DAY_BUCKETS;
				return b - sh <= o ? [a - sh, b - sh] : null;
			}
			case "C": {
				const k = c.k as number;
				const d = (dayIdx[o] as number) - k;
				if (d < 0) return null;
				const D = days[d] as { first: number; end: number };
				return [D.first, k === 0 ? o : D.end];
			}
			case "D": {
				const d0 = dayIdx[o] as number;
				for (let d = d0 - 1; d >= 0 && d >= d0 - 7; d--) {
					const D = days[d] as { first: number; end: number; wd: number };
					if (D.wd === c.wd) return [D.first, D.end];
				}
				return null;
			}
			case "W":
				return (
					this.prevWeek[dayIdx[o] as number] as ([number, number] | null)[]
				)[c.workdays ? 1 : 0] as [number, number] | null;
			default:
				return null;
		}
	}

	/** Feature value of candidate c at origin o for the target [a, b) against the sums P (sandbox model3b.ts xOf). */
	value(
		c: PaceCandidate,
		P: SpanSums,
		o: number,
		a: number,
		b: number,
	): number {
		if (c.family === "T") {
			if (a < 0 || b > this.cal.n || b <= a) return Number.NaN;
			const p =
				c.hour !== undefined
					? this.counts(
							this.hourCount,
							c.hour,
							(i) => Math.floor((this.cal.minute[i] as number) / 60) === c.hour,
						)
					: this.counts(
							this.wdCount,
							c.wd as number,
							(i) => this.cal.wd[i] === c.wd,
						);
			return ((p[b] as number) - (p[a] as number)) / (b - a);
		}
		const sp = this.span(c, o, a, b);
		return sp ? lr(P, sp[0], sp[1]) : Number.NaN;
	}
}

/**
 * Mean units per bucket by (group, local 5-minute slot) over the training days,
 * censored buckets left out; partial days (under 270 buckets) skipped (sandbox lib.ts baseline).
 * `groupOf` maps a weekday (0 = Monday) to a group. Returns the per-group slot means.
 */
export function baselineProfile(
	cal: PaceCalendar,
	units: ArrayLike<number>,
	censored: ArrayLike<number>,
	groupOf: ArrayLike<number>,
	groups: number,
	trainDay: (d: number) => boolean,
): Float64Array[] {
	const sum = Array.from(
		{ length: groups },
		() => new Float64Array(DAY_BUCKETS),
	);
	const cnt = Array.from(
		{ length: groups },
		() => new Float64Array(DAY_BUCKETS),
	);
	cal.days.forEach((D, d) => {
		if (!trainDay(d) || D.end - D.first < 270) return;
		const g = groupOf[D.wd] as number;
		const s = sum[g] as Float64Array;
		const c = cnt[g] as Float64Array;
		for (let i = D.first; i < D.end; i++) {
			if (censored[i]) continue;
			const slot = Math.floor((cal.minute[i] as number) / 5);
			s[slot] = (s[slot] as number) + (units[i] as number);
			c[slot] = (c[slot] as number) + 1;
		}
	});
	return sum.map((s, g) =>
		s.map((v, slot) => {
			const c = (cnt[g] as Float64Array)[slot] as number;
			return c ? v / c : 0;
		}),
	);
}

/** Prefix sums of a baseline profile laid over the first n buckets of the calendar. */
export function baselinePrefix(
	cal: PaceCalendar,
	profile: ArrayLike<number>[],
	groupOf: ArrayLike<number>,
	n: number,
): Float64Array {
	const p = new Float64Array(n + 1);
	for (let i = 0; i < n; i++) {
		const g = groupOf[cal.wd[i] as number] as number;
		const v = (profile[g] as ArrayLike<number>)[
			Math.floor((cal.minute[i] as number) / 5)
		] as number;
		p[i + 1] = (p[i] as number) + v;
	}
	return p;
}
